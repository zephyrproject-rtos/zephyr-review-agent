"""The triage as one comment on the issue."""

from __future__ import annotations

import re

from ..review.github_api import file_url
from ..review.render import guard_mentions
from .decide import Proposal
from .fixes import Comparison
from .schema import Triage

TAG = "zephyr-triage"
VERDICT_LINES = {
    "confirmed": "✅ **Confirmed by reading the code**",
    "plausible": "🔎 **Likely cause found**, not fully confirmed",
    "cannot_confirm": "❔ **No cause found**",
    "not_a_bug": "ℹ️ **Looks like expected behaviour**",
    "needs_info": "❓ **More information needed**",
}
RELATION_LINES = {
    "same_fix": "Same fix as found here.",
    "same_cause_different_fix": "Same cause, fixed another way.",
    "different_cause": "Addresses something else than found here.",
    "unrelated": "Does not try to fix this issue.",
    "cannot_tell": "Could not be compared.",
}
COMPARED_NOTE = "The analysis above was made without these pull requests, which were compared with it afterwards."
ADVISORY = (
    "<sub>This triage is generated by a language model that read the source tree. Nothing was built or run. "
    "It is advisory; verify before acting on it.</sub>"
)


def marker(tag: str = TAG) -> str:
    return f"<!-- {tag} -->"


def commit_marker(commit: str, tag: str = TAG) -> str:
    return f"<!-- {tag}:commit:{commit} -->"


def _sentence(text: str) -> str:
    t = guard_mentions(" ".join((text or "").split()))
    return t if not t or t[-1] in ".!?:`)" else t + "."


def _brief(text: str, sentences: int = 3, chars: int = 500) -> str:
    """The first sentences of what a model wrote, for when it wrote a page where a line was asked for."""
    t = " ".join((text or "").split())
    if len(t) <= chars:
        return _sentence(t)
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z`])", t)
    kept: list[str] = []
    for part in parts[:sentences]:
        if kept and len(" ".join(kept + [part])) > chars:
            break
        kept.append(part)
    out = " ".join(kept)
    if len(out) > chars:
        return guard_mentions(out[:chars].rsplit(" ", 1)[0].rstrip(",;:.")) + " …"
    return _sentence(out)


def render_comment(
    triage: Triage,
    proposal: Proposal,
    commit: str,
    *,
    repo: str = "",
    api_url: str = "https://api.github.com",
    tag: str = TAG,
    applied: dict[str, list[str]] | None = None,
    comparisons: list[Comparison] | None = None,
) -> str:
    """``applied`` names what the run did to the issue itself (labels added, assignees set); everything
    else under "Proposed triage" is a proposal for a maintainer."""
    applied = applied or {}
    head = VERDICT_LINES[triage.verdict] + f" · confidence {triage.confidence}"
    if triage.provisional:
        head += " · the analysis was limited"
    out = [
        marker(tag),
        commit_marker(commit, tag),
        "## 🤖 AI triage (advisory)",
        "",
        head,
    ]
    c = triage.cause
    if not (triage.located and c is not None):
        out += ["", _brief(triage.summary)]
    else:
        where = f"{c.file}:{c.line}" if c.line else c.file
        link = f"[`{where}`]({file_url(repo, commit, c.file, c.line or None, api_url)})" if repo else f"`{where}`"
        out += ["", "### Likely cause", "", f"{link}: {_brief(c.explanation)}"]
    k = triage.culprit
    if triage.located and k is not None:
        short = k.commit[:12]
        ref = f"{repo}@{short}" if repo else f"`{short}`"
        line = f"{ref} {_quote(k.subject)}" + (f", {k.date}" if k.date else "")
        if k.releases:
            line += f", first released in {k.releases[0]}"
        out += ["", "### Introduced by", "", f"{line} · confidence {k.confidence}", "", _brief(k.reason, 2, 300)]
    if triage.fix and triage.located:
        out += ["", "### Suggested fix", "", _brief(triage.fix, 2, 400)]
        if triage.patch:
            out += ["", "```diff", triage.patch.replace("```", "'''"), "```"]
    if comparisons:
        out += ["", "### Proposed fixes", "", COMPARED_NOTE, ""]
        for c in comparisons:
            line = f"- #{c.number} ({c.state}): **{RELATION_LINES[c.relation]}** {_brief(c.assessment, 2, 300)}"
            if c.concerns:
                line += f" Open: {_brief(c.concerns, 2, 300)}"
            out.append(line)
    if triage.questions:
        out += ["", "### Questions for the reporter", ""] + [f"- {_sentence(q)}" for q in triage.questions]
    filed = _filing(triage, proposal, applied)
    if filed:
        out += ["", "### Proposed triage", ""] + filed
    if triage.duplicates:
        out += ["", "### Possibly related", ""] + [f"- #{n}: {_sentence(why)}" for n, why in triage.duplicates]
    out += ["", "---", ADVISORY]
    return "\n".join(out) + "\n"


def _quote(text: str) -> str:
    return '"' + guard_mentions(text.replace('"', "'")) + '"' if text else ""


def _filing(triage: Triage, p: Proposal, applied: dict[str, list[str]]) -> list[str]:
    out = []
    added = applied.get("labels") or []
    if p.labels:
        rest = [lab for lab in p.labels if lab not in added]
        if added:
            out.append("- Labels added: " + ", ".join(f"`{lab}`" for lab in added if lab in p.labels))
        if rest:
            out.append("- Labels: " + ", ".join(f"`{lab}`" for lab in rest))
    if triage.priority and triage.located:
        label = p.priority or f"priority: {triage.priority}"
        verb = "Priority set" if label in added else "Priority"
        reason = f", because {_lower(triage.priority_reason)}" if triage.priority_reason else ""
        out.append(f"- {verb}: `{label}`{_sentence(reason) if reason else ''}")
    assigned = applied.get("assignees") or []
    if assigned:
        out.append("- Assigned: " + ", ".join(f"`{a}`" for a in assigned))
    if p.areas:
        out.insert(0, "- Area: " + ", ".join(p.areas))
    if not assigned and p.maintainers:
        who = ", ".join(f"`{m}`" for m in p.maintainers)
        out.append(f"- Maintained by {who}" + (f" ({p.area})" if p.area else ""))
    return out


def _lower(text: str) -> str:
    t = " ".join(text.split()).rstrip(".")
    return t[:1].lower() + t[1:] if t and not t[:2].isupper() else t
